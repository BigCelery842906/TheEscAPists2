    {
        string trimmedItemName = ItemName.Replace(" ", "");

        int itemID = -1;

        if (itemIDReferences.ContainsKey(trimmedItemName))
        {
            itemID = itemIDReferences[trimmedItemName];
        }
        
        return itemID;
    }

    public static int[] GetRecipeIngredientsFromName(string recipeName)
    {
        string trimmedItemName = recipeName.Replace(" ", "");
        int[] recipeingredientsID = [-1, -1, -1];
        
        if (apworldBlueprints.ContainsKey(trimmedItemName))
        {
            recipeingredientsID = apworldBlueprints[trimmedItemName];
        }
        
        return recipeingredientsID;
    }

